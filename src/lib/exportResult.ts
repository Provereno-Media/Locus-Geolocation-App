import type { Coordinates, GeolocationResult } from '../services/geo/types';
import { formatDecimalPair, formatDms } from './coords';

export interface ChatLine {
  role: 'user' | 'model';
  text: string;
}

export interface ExportContext {
  /** SHA-256 of the analysed image bytes, hex */
  imageSha256: string;
  chat?: ChatLine[];
}

export const APP_URL = 'https://github.com/Provereno-Media/Locus-Geolocation-App';

const CAVEAT =
  'Model output for verification, not an established fact. Confidence is self-reported by the model and not calibrated.';

export async function sha256Hex(bytes: BufferSource): Promise<string> {
  const digest = await crypto.subtle.digest('SHA-256', bytes);
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, '0')).join('');
}

export function base64ToBytes(base64: string): Uint8Array {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

/** Neutral file name: no place names, only the analysis date and the start of the image hash. */
export function exportFileName(result: GeolocationResult, ctx: ExportContext, extension: string): string {
  return `locus-${result.analyzedAt.slice(0, 10)}-${ctx.imageSha256.slice(0, 8)}.${extension}`;
}

function formatUtc(iso: string): string {
  const date = new Date(iso);
  return Number.isNaN(date.getTime()) ? iso : `${date.toISOString().slice(0, 16).replace('T', ' ')} UTC`;
}

function groundingLabel(result: GeolocationResult): string {
  return result.groundingTool === 'search' ? 'Google Search' : 'Google Maps';
}

function modelLabel(result: GeolocationResult): string {
  return result.modelFallbackFrom ? `${result.model} (fallback from ${result.modelFallbackFrom})` : result.model;
}

/** Keeps model text from breaking list items and link syntax. */
function inline(text: string): string {
  return text.replace(/\s*\n\s*/g, ' ').trim();
}

function linkTitle(text: string): string {
  return inline(text).replace(/([[\]\\])/g, '\\$1');
}

function codeSpan(text: string): string {
  const clean = inline(text);
  return clean.includes('`') ? `\`\` ${clean} \`\`` : `\`${clean}\``;
}

function list(items: string[], format: (item: string) => string = inline): string {
  return items.map((item) => `- ${format(item)}`).join('\n');
}

export function buildMarkdownReport(result: GeolocationResult, ctx: ExportContext): string {
  const c = result.coordinates;
  const lines: string[] = [
    '# LOCUS geolocation report',
    '',
    `> ${CAVEAT}`,
    '',
    `- **Location:** ${inline(result.locationName)}`,
    `- **Coordinates:** ${c ? `${formatDecimalPair(c)} (${formatDms(c)})` : 'not determined'}`,
    `- **Model confidence:** ${Math.round(result.confidence * 100)}%`,
    `- **Analysed:** ${formatUtc(result.analyzedAt)}`,
    `- **Model:** ${modelLabel(result)}; grounding: ${groundingLabel(result)}; mode: ${result.mode}`,
    `- **Image SHA-256:** \`${ctx.imageSha256}\``,
  ];

  const section = (title: string, body: string) => {
    if (body.trim()) lines.push('', `## ${title}`, '', body);
  };

  section('Reasoning', result.description.trim());
  section('Evidence (reported by the model)', list(result.evidence));
  section('Text in the image', list(result.extractedText));
  section('Symbols', list(result.identifiedSymbols));
  section(
    'Sources (from grounding metadata)',
    result.sources
      .map((s, i) => `${i + 1}. [${linkTitle(s.title)}](<${s.uri}>) — ${s.type === 'maps' ? 'Google Maps' : 'web'}`)
      .join('\n'),
  );
  section('Queries executed by Google', list(result.groundingQueries, codeSpan));
  section('Queries reported by the model (unverified)', list(result.modelReportedQueries, codeSpan));
  if (c) {
    section(
      'Check on maps',
      mapLinks(c)
        .map((l) => `- [${l.label}](<${l.url}>)`)
        .join('\n'),
    );
  }
  section(
    'Analysis chat',
    (ctx.chat ?? []).map((m) => `**${m.role === 'user' ? 'Question' : 'LOCUS'}:** ${m.text.trim()}`).join('\n\n'),
  );

  lines.push('', '---', '', `Generated by [LOCUS](${APP_URL}).`, '');
  return lines.join('\n');
}

function xml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function plainDescription(result: GeolocationResult): string {
  return [
    CAVEAT,
    `Model confidence: ${Math.round(result.confidence * 100)}%.`,
    result.evidence.length > 0 ? `Evidence: ${result.evidence.map(inline).join('; ')}` : '',
  ]
    .filter(Boolean)
    .join('\n');
}

/** Null when the result has no coordinates. */
export function buildKml(result: GeolocationResult, ctx: ExportContext): string | null {
  const c = result.coordinates;
  if (!c) return null;
  const data: [string, string][] = [
    ['confidence', result.confidence.toFixed(2)],
    ['model', modelLabel(result)],
    ['grounding', groundingLabel(result)],
    ['analyzedAt', result.analyzedAt],
    ['imageSha256', ctx.imageSha256],
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
  <Document>
    <name>${xml(`LOCUS ${result.analyzedAt.slice(0, 10)}`)}</name>
    <Placemark>
      <name>${xml(inline(result.locationName))}</name>
      <description>${xml(plainDescription(result))}</description>
      <ExtendedData>
${data.map(([k, v]) => `        <Data name="${k}"><value>${xml(v)}</value></Data>`).join('\n')}
      </ExtendedData>
      <Point>
        <coordinates>${c.lng},${c.lat},0</coordinates>
      </Point>
    </Placemark>
  </Document>
</kml>
`;
}

/** Null when the result has no coordinates. */
export function buildGeoJson(result: GeolocationResult, ctx: ExportContext): string | null {
  const c = result.coordinates;
  if (!c) return null;
  const feature = {
    type: 'Feature',
    geometry: { type: 'Point', coordinates: [c.lng, c.lat] },
    properties: {
      name: inline(result.locationName),
      note: CAVEAT,
      confidence: result.confidence,
      evidence: result.evidence,
      model: result.model,
      modelFallbackFrom: result.modelFallbackFrom ?? null,
      grounding: result.groundingTool,
      mode: result.mode,
      analyzedAt: result.analyzedAt,
      imageSha256: ctx.imageSha256,
      sources: result.sources,
    },
  };
  return `${JSON.stringify({ type: 'FeatureCollection', features: [feature] }, null, 2)}\n`;
}

export interface MapLink {
  label: string;
  url: string;
}

/** Opening any of these sends the coordinates to that service. */
export function mapLinks(c: Coordinates): MapLink[] {
  const lat = c.lat.toFixed(6);
  const lng = c.lng.toFixed(6);
  return [
    { label: 'Google Maps', url: `https://www.google.com/maps/search/?api=1&query=${lat},${lng}` },
    { label: 'Google Earth', url: `https://earth.google.com/web/search/${lat},${lng}` },
    { label: 'OpenStreetMap', url: `https://www.openstreetmap.org/?mlat=${lat}&mlon=${lng}#map=17/${lat}/${lng}` },
    { label: 'Mapillary', url: `https://www.mapillary.com/app/?lat=${lat}&lng=${lng}&z=17` },
    { label: 'Copernicus Browser', url: `https://browser.dataspace.copernicus.eu/?zoom=15&lat=${lat}&lng=${lng}` },
  ];
}

export function downloadText(content: string, fileName: string, mimeType: string): void {
  const url = URL.createObjectURL(new Blob([content], { type: mimeType }));
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
